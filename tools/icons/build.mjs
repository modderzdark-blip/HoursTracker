// Extracts the icons named in icons.json from a clone of https://github.com/game-icons/icons
// (CC BY 3.0, see public/assets/CREDITS.md) into src/ui/iconPaths.ts.
// Usage: node tools/icons/build.mjs <path-to-game-icons-clone>
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const repo = process.argv[2];
if (repo === undefined) throw new Error('usage: node tools/icons/build.mjs <game-icons clone>');
const wanted = JSON.parse(readFileSync(new URL('./icons.json', import.meta.url), 'utf8'));

/**
 * Every icon in the clone: name → { author, file }. The 'badges' set draws its shapes small inside
 * a badge frame, so another author's icon of the same name wins.
 */
const index = new Map();
for (const author of readdirSync(repo).sort()) {
  const dir = join(repo, author);
  if (!statSync(dir).isDirectory() || author.startsWith('.')) continue;
  for (const f of readdirSync(dir)) {
    if (!f.endsWith('.svg')) continue;
    const name = f.slice(0, -4);
    const prev = index.get(name);
    if (prev === undefined || prev.author === 'badges')
      index.set(name, { author, file: join(dir, f) });
  }
}

const out = [];
const credits = [];
for (const [key, source] of Object.entries(wanted)) {
  const hit = index.get(source);
  if (hit === undefined) throw new Error(`icon not found: ${source}`);
  const svg = readFileSync(hit.file, 'utf8');
  const ds = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)]
    .map((m) => m[1])
    .filter((d) => d !== 'M0 0h512v512H0z');
  if (ds.length === 0) throw new Error(`no path in ${source}`);
  out.push(`  ${key}: '${ds.join(' ')}',`);
  credits.push(`${key}: ${source} by ${hit.author}`);
}

const header = `/**
 * Icon shapes (512 × 512) from game-icons.net (https://github.com/game-icons/icons), CC BY 3.0.
 * Generated by tools/icons/build.mjs from tools/icons/icons.json; do not edit by hand.
 *
${credits.map((c) => ` * - ${c}`).join('\n')}
 */
`;
writeFileSync(
  new URL('../../src/ui/iconPaths.ts', import.meta.url),
  `${header}export const ICON_PATHS = {\n${out.join('\n')}\n} as const;\n`,
);
console.log(`wrote ${out.length} icons`);
