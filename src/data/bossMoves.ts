/**
 * Movesets of the bosses met past the fourth chapter (Endless Adventure, the Demon Tower, Boss
 * Challenge and Hunts): the Headsman, the Bone Cantor, the Twin Maw, the Ossuary Queen and the
 * Hollow Twin. Same data model as src/data/bosses.ts: every wind-up is its telegraph, area
 * attacks show ground indicators, bullet patterns are slow enough to weave through.
 */
import type { EmitDef, HitSpec, ProjectileDef } from './combatTypes';
import type { EnemyAttackDef } from './enemies';

const heavy = (damage: number, shape: HitSpec['shape'], extra: Partial<HitSpec> = {}): HitSpec => ({
  damage,
  poise: 0,
  reaction: 'knockback',
  knockback: 1.8,
  hitStopMs: 80,
  shake: 0.45,
  shape,
  ...extra,
});

/** Light chip damage for bullets and ticks (many of them can land in a pattern). */
const chip = (damage: number, extra: Partial<HitSpec> = {}): HitSpec =>
  heavy(
    damage,
    { kind: 'circle', radius: 0.4, forward: 0 },
    { reaction: 'flinch', knockback: 0.4, hitStopMs: 30, shake: 0.08, ...extra },
  );

/** Slow glowing pattern bullet. */
const orb = (color: number, speed: number, rangeM = 18): ProjectileDef => ({
  visual: 'orb',
  color,
  speed,
  radius: 0.36,
  rangeM,
  pierce: false,
  homing: 0,
  height: 1.3,
});

/** `count` bullets in a ring, released `bursts` times `everyMs` apart, each burst turned. */
const rings = (
  spec: HitSpec,
  projectile: ProjectileDef,
  count: number,
  bursts: number,
  everyMs: number,
  turnDeg: number,
): EnemyAttackDef['hits'] =>
  Array.from({ length: bursts }, (_, i) => ({
    offsetMs: i * everyMs,
    spec,
    emit: {
      kind: 'projectile' as const,
      projectile,
      count,
      spreadDeg: 0,
      aim: 'facing' as const,
      pattern: 'ring' as const,
      angleOffsetDeg: i * turnDeg,
    },
  }));

